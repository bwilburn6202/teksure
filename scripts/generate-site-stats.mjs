/**
 * generate-site-stats.mjs
 * -----------------------
 * Writes src/data/site-stats.ts — the "how much is on TekSure" numbers used in
 * homepage and hub copy.
 *
 * WHY CODEGEN INSTEAD OF A RUNTIME IMPORT:
 * The obvious version of this file just does `import { guides } from './guides'`
 * and exports `guides.length`. Do not do that. `guides.ts` pulls in 325 batch
 * files (~19 MB of source), so any page importing it inherits the entire guide
 * corpus. The homepage needs exactly two numbers — importing the corpus to
 * render "4,000+" would put multiple megabytes in front of a user on rural DSL
 * before they see anything. Counting here at build time keeps the runtime
 * module down to two integers.
 *
 * Runs in prebuild, alongside generate-tools-directory.mjs.
 */

import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const DATA = join(ROOT, 'src', 'data');

// ── Count guides ─────────────────────────────────────────────────────────────
// Every guide object carries a unique `slug:`. Count slug declarations across
// the batch files rather than parsing TypeScript.
let guideCount = 0;
const seenSlugs = new Set();
for (const file of readdirSync(DATA)) {
  if (!/^guides(-batch-\d+|-expansion|-spanish)?\.ts$/.test(file)) continue;
  const src = readFileSync(join(DATA, file), 'utf8');
  // Leading [{,\s] rather than ^\s+ so guides written as single-line object
  // literals — `{ slug: '...', title: '...' }`, ~301 of them — are counted too,
  // while `canonicalSlug:` stays excluded. Same bug fixed in dev-loop.mjs (cycle 86b);
  // this generator was written before that fix and inherited it.
  for (const m of src.matchAll(/(?:^|[{,\s])slug:\s*['"`]([^'"`]+)['"`]/gm)) {
    if (seenSlugs.has(m[1])) continue; // duplicate slugs are filtered at runtime
    seenSlugs.add(m[1]);
    guideCount++;
  }
}

// ── Count tools ──────────────────────────────────────────────────────────────
// Same source of truth the tools directory uses: concrete /tools/* routes.
const appTsx = readFileSync(join(ROOT, 'src', 'App.tsx'), 'utf8');
const toolPaths = new Set();
for (const m of appTsx.matchAll(/path="(\/tools\/[^"]+)"/g)) {
  const p = m[1];
  if (p.includes(':') || p.includes('*') || p === '/tools/all') continue;
  toolPaths.add(p);
}
const toolCount = toolPaths.size;

// ── Friendly, always-true rounding ───────────────────────────────────────────
// Round DOWN so the claim stays true even if content lands between builds.
function friendlyFloor(n) {
  const step = n < 500 ? 50 : 100;
  return Math.floor(n / step) * step;
}
const plus = (n) => `${friendlyFloor(n).toLocaleString('en-US')}+`;

const out = `// AUTO-GENERATED by scripts/generate-site-stats.mjs — do not edit by hand.
// Regenerated on every build (prebuild).
//
// These numbers used to be hardcoded in Landing.tsx, Tools.tsx and
// SiteIndex.tsx and had drifted badly (homepage claimed "2,500+ guides"
// against ~${guideCount}; /tools claimed "150+" against ${toolCount}). Stale numbers read
// as carelessness to a cautious audience. Use these constants in copy —
// never type a count literal into a component.

/** Exact counts at build time. */
export const GUIDE_COUNT = ${guideCount};
export const TOOL_COUNT = ${toolCount};

/** Display strings, rounded down so the claim is always true. */
export const GUIDE_COUNT_LABEL = '${plus(guideCount)}';
export const TOOL_COUNT_LABEL = '${plus(toolCount)}';
`;

writeFileSync(join(DATA, 'site-stats.ts'), out);
console.log(
  `[site-stats] ${guideCount} guides -> "${plus(guideCount)}", ${toolCount} tools -> "${plus(toolCount)}"`
);
