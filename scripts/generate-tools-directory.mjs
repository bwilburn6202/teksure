/**
 * generate-tools-directory.mjs
 * ----------------------------
 * Reads every live tool slug from src/data/tools-registry.ts and writes
 * src/data/tools-directory.ts — the data source for the "All Tools A–Z"
 * directory page (/tools/all). Runs in prebuild, so the directory always
 * matches the real route table and no tool page can be orphaned.
 */

import { readFileSync, writeFileSync } from 'fs';
import { readToolSlugs } from './tool-slugs.mjs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

const ACRONYMS = new Set([
  'aarp', 'aaa', 'va', 'irs', 'ssa', 'atm', 'gps', 'wifi', 'tv', 'pc', 'usb',
  'pdf', 'qr', 'ai', 'acp', 'adu', 'diy', 'dmv', 'ups', 'usps', 'cvs', 'hsa',
  'fsa', 'cd', 'dvd', 'hdmi', 'sim', 'sms', 'faq', 'id', 'rmd', '401k', 'ira',
]);

function labelFromSlug(slug) {
  return slug
    .split('-')
    .map((w) => {
      if (ACRONYMS.has(w.toLowerCase())) return w.toUpperCase();
      if (/^\d/.test(w)) return w;
      return w.charAt(0).toUpperCase() + w.slice(1);
    })
    .join(' ');
}

// Source of truth is src/data/tools-registry.ts, not the route table — App.tsx
// now has a single dynamic /tools/:slug route.
const paths = new Set(readToolSlugs().map((s) => `/tools/${s}`));

const items = [...paths].sort().map((p) => ({
  path: p,
  label: labelFromSlug(p.replace('/tools/', '')),
}));

const out = `// AUTO-GENERATED by scripts/generate-tools-directory.mjs — do not edit by hand.
// Regenerated on every build (prebuild). ${items.length} tools.

export interface ToolDirectoryItem {
  path: string;
  label: string;
}

export const toolsDirectory: ToolDirectoryItem[] = [
${items.map((i) => `  { path: '${i.path}', label: ${JSON.stringify(i.label)} },`).join('\n')}
];
`;

writeFileSync(join(ROOT, 'src', 'data', 'tools-directory.ts'), out);
console.log(`[generate-tools-directory] wrote ${items.length} tools to src/data/tools-directory.ts`);
